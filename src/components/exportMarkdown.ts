import type { CompanyRef, CompetitorDossier, CounterAttackPlan, Evidence, LaunchPrediction } from "@/lib/types";
import { byHeadcountDesc } from "./format";

const KIND: Record<Evidence["kind"], string> = { job: "Job", hire: "Hire", news: "News" };
const oneLine = (s: string) => s.replace(/\s+/g, " ").trim();
const quote = (s: string) => `> ${oneLine(s)}`;

export function reportToMarkdown(opts: {
  you: CompanyRef | null;
  dossiers: CompetitorDossier[];
  predictions: LaunchPrediction[];
  plans: CounterAttackPlan[];
  engine?: "claude" | "rules" | null;
  mock: boolean;
  creditsUsed: number;
}): string {
  const { you, dossiers, predictions, plans, engine, mock } = opts;
  const date = new Date().toISOString().slice(0, 10);
  const rivals = dossiers.map((d) => d.company.name).join(", ");
  const source = [
    mock ? "Demo data (fictional)" : "Live Crustdata data",
    engine === "rules" ? "predictions by the rules engine" : engine === "claude" ? "predictions by Claude" : null,
  ]
    .filter(Boolean)
    .join(", ");
  const jobUrl = new Map<string, string | null>();
  const hireUrl = new Map<string, string | null>();
  for (const d of dossiers) {
    for (const j of d.jobs) jobUrl.set(String(j.id), j.url);
    for (const h of d.recentHires) hireUrl.set(String(h.personId), h.profileUrl);
  }
  const evLine = (e: Evidence) => {
    const url = e.kind === "news" ? e.ref : e.kind === "job" ? jobUrl.get(e.ref) : hireUrl.get(e.ref);
    return `- ${KIND[e.kind]}: ${url ? `[${e.text}](${url})` : e.text}`;
  };

  const out: string[] = [];
  out.push(`# Secret Product Spy: ${you?.name ?? "Report"} vs ${rivals || "competitors"}`);
  out.push(`_${date} · ${source}_`, "");

  out.push(`## Predicted launches`, "");
  if (predictions.length === 0) out.push("No launch signal strong enough to call.", "");
  for (const p of predictions) {
    out.push(`### ${p.competitorName}: ${p.headline}`);
    out.push(`**${p.confidence} confidence (${p.confidenceScore}/100)** · ${p.area} · expected ${p.expectedWindow}`, "");
    out.push(oneLine(p.summary), "");
    out.push(`**Threat to ${you?.name ?? "us"}:** ${oneLine(p.threatToYou)}`, "");
    out.push(`Evidence:`, ...p.evidence.map(evLine), "");
  }

  if (plans.length) out.push(`## Counter-attack`, "");
  for (const plan of plans) {
    const pred = predictions.find((p) => p.id === plan.predictionId);
    out.push(`### Against ${pred ? `${pred.competitorName}: ${pred.headline}` : plan.predictionId}`, "");
    if (plan.actions.length) out.push(...plan.actions.map((a, i) => `${i + 1}. ${oneLine(a)}`), "");

    if (plan.targets.length) {
      out.push(`#### Accounts to pitch now`, "");
      for (const t of byHeadcountDesc(plan.targets)) {
        const size = t.company.headcount ? `, ${t.company.headcount.toLocaleString("en-US")} people` : "";
        const buyers = t.buyers.map((b) => `${b.name}${b.title ? ` (${b.title})` : ""}`).join("; ");
        out.push(`- **${t.company.name}**${t.company.domain ? ` (${t.company.domain}${size})` : size}: ${oneLine(t.whyNow)}`);
        if (buyers) out.push(`  - Buyer: ${buyers}`);
        if (t.quote) out.push(`  - Proof ([source](${t.sourceUrl})):`, `    ${quote(t.quote)}`);
        else out.push(`  - Source: ${t.sourceUrl}`);
      }
      out.push("");
    }

    if (plan.emails.length) {
      out.push(`#### Email drafts`, "");
      for (const e of plan.emails) {
        out.push(`**To:** ${e.to.name}${e.to.title ? `, ${e.to.title}` : ""} at ${e.to.company}  `);
        out.push(`**Subject:** ${e.subject}`, "");
        out.push(...e.body.split("\n").map((l) => (l ? `> ${l}` : ">")), "");
      }
    }
  }

  // Customers of competitors that had no plan (no prediction) are still worth handing over.
  const planned = new Set(plans.flatMap((p) => p.targets.map((t) => t.company.crustdataCompanyId)));
  const extra = dossiers.flatMap((d) => (d.targets ?? []).filter((t) => !planned.has(t.company.crustdataCompanyId)));
  if (extra.length) {
    out.push(`## Other competitor customers`, "");
    for (const t of byHeadcountDesc(extra)) out.push(`- **${t.company.name}** uses ${t.competitorName}${t.quote ? `: "${oneLine(t.quote)}"` : ""} ([source](${t.sourceUrl}))`);
    out.push("");
  }

  out.push(`---`, `Generated by Secret Product Spy from public hiring data (Crustdata). Verify before outreach.`);
  return out.join("\n");
}
